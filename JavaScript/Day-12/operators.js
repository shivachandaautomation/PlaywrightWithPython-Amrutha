// Logical Operators

// && - AND 
// || - OR 
// ! - NOT 

const a = true;
const b = false;

// AND: true only when both are true
const andResult = a && b; // false

// OR: true when at least one is true
const orResult = a || b; // true

// NOT: reverses the boolean value
const notResult = !a; // false

console.log("a && b =", andResult);
console.log("a || b =", orResult);
console.log("!a =", notResult);




